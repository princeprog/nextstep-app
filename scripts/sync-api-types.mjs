// Regenerates src/lib/api/schema.d.ts from the API's published OpenAPI document.
// Default source: the sibling nextstep-api checkout. Override with NEXTSTEP_OPENAPI (a file path or URL).
import { existsSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

const here = dirname(fileURLToPath(import.meta.url))
const source = process.env.NEXTSTEP_OPENAPI ?? resolve(here, "../../nextstep-api/openapi/openapi.yaml")
const target = resolve(here, "../src/lib/api/schema.d.ts")

const isUrl = /^https?:\/\//.test(source)
if (!isUrl && !existsSync(source)) {
  console.error("OpenAPI document not found: " + source + "\nSet NEXTSTEP_OPENAPI to the nextstep-api openapi/openapi.yaml path.")
  process.exit(1)
}

const ast = await openapiTS(isUrl ? new URL(source) : pathToFileURL(source))
const header = "// Generated by scripts/sync-api-types.mjs from the NextStep API OpenAPI document. Do not edit by hand.\n"
writeFileSync(target, header + astToString(ast))
console.log("Wrote " + target)

